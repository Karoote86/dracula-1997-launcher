"""Makes the public copy of hires_patch.py: every hex string literal of >= 4 bytes that also occurs in the
original game EXE is replaced by O(offset, length, sha256-prefix), which reads those bytes from the user's own
EXE at run time and verifies them. The result contains no bytes of the game; its output is identical.

Usage: py -I redact_patch_script.py <hires_patch.py> <Dracula_nocd.exe> <out.py>
"""
import hashlib, re, sys

src, exe, out = sys.argv[1:4]
text = open(src, encoding='utf-8').read()
base = open(exe, 'rb').read()

HELPER = '''
# --- public version: original game bytes are not stored in this file. O() reads them from the EXE given on
# --- the command line and checks them against a SHA-256 prefix (generated by redact_patch_script.py).
import hashlib as _hl
_O_BASE = None
def O(off, n, h):
    global _O_BASE
    if _O_BASE is None:
        _O_BASE = open([a for a in sys.argv[1:] if not a.startswith('--')][0], 'rb').read()
    b = _O_BASE[off:off + n]
    if _hl.sha256(b).hexdigest()[:16] != h:
        sys.exit(f'input EXE does not match at file offset 0x{off:x} - wrong Dracula.exe version?')
    return b.hex()
'''

count = 0
def repl(m):
    global count
    q, hx = m.group(1), m.group(2)
    if len(hx) % 2 or len(hx) < 8: return m.group(0)
    b = bytes.fromhex(hx)
    off = base.find(b)
    if off < 0: return m.group(0)
    count += 1
    return f'O(0x{off:x}, {len(b)}, {hashlib.sha256(b).hexdigest()[:16]!r})'

body = re.sub(r"(['\"])([0-9a-fA-F]+)\1", repl, text)
# insert the helper after the first block of imports
m = re.search(r'^import [^\n]*\n', body, re.M)
assert m, 'no import line found'
body = body[:m.end()] + HELPER + body[m.end():]
open(out, 'w', encoding='utf-8', newline='\n').write(body)
print(f'{count} literals replaced -> {out}')
