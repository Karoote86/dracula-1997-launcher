class Asm:
    """Tiny x86 emitter: raw hex + rel8/rel32 jumps to labels or absolute addresses."""
    def __init__(self, base):
        self.base, self.b, self.labels, self.fix = base, bytearray(), {}, []
    def here(self): return self.base + len(self.b)
    def label(self, name): self.labels[name] = self.here()
    def raw(self, hexstr, *dwords):
        self.b += bytes.fromhex(hexstr)
        for d in dwords: self.b += struct.pack('<I', d & 0xffffffff)
    def data(self, bs):                    # raw bytes, returns their VA
        va = self.here(); self.b += bs; return va
    def j8(self, opcode, name):            # short jcc/jmp to label
        self.b += bytes([opcode, 0]); self.fix.append(('r8', len(self.b) - 1, name))
    def rel32(self, opcode, target):      # E8 call / E9 jmp to label or absolute VA
        self.b += bytes([opcode]); self.fix.append(('r32', len(self.b), target)); self.b += b'\0' * 4
    def jz32(self, target):               # 0F 84 near jz
        self.jcc32(0x84, target)
    def jcc32(self, cc, target):          # 0F 8x near jcc (0x84 jz, 0x8d jge, ...)
        self.b += bytes([0x0f, cc]); self.fix.append(('r32', len(self.b), target)); self.b += b'\0' * 4
    def finish(self):
        for kind, pos, t in self.fix:
            tgt = self.labels[t] if isinstance(t, str) else t
            if kind == 'r8':
                rel = tgt - (self.base + pos + 1)
                assert -128 <= rel <= 127, f'short jump to {t} out of range'
                self.b[pos] = rel & 0xff
            else:
                struct.pack_into('<i', self.b, pos, tgt - (self.base + pos + 4))
        return bytes(self.b)


def iat_address(data, name):
    """VA of the import address table slot of an imported function."""
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    opt = pe + 24
    imp_rva = struct.unpack_from('<I', data, opt + 104)[0]
    nsec = struct.unpack_from('<H', data, pe + 6)[0]
    sec = opt + struct.unpack_from('<H', data, pe + 20)[0]
    def r2o(rva):
        for i in range(nsec):
            vs, va_, rs, rp = struct.unpack_from('<IIII', data, sec + i * 40 + 8)
            if va_ <= rva < va_ + max(vs, rs): return rva - va_ + rp
    o = r2o(imp_rva)
    while True:
        oft, _, _, dll, ft = struct.unpack_from('<IIIII', data, o)
        if not dll: break
        t, slot = r2o(oft or ft), ft
        while True:
            v = struct.unpack_from('<I', data, t)[0]
            if not v: break
            if not v & 0x80000000:
                s = r2o(v) + 2
                if data[s:data.index(b'\0', s)].decode() == name: return 0x400000 + slot
            t += 4; slot += 4
        o += 20
    raise KeyError(name)


