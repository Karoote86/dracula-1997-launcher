def level_check(W, H):
    assert (W - 160) % 40 == 0 and H % 40 == 0, 'battle view (W-160) x H must be multiples of 40 (tile size)'
    TX, TY = (W - 160) // 40, H // 40          # visible tiles (orig 12 x 12)
    assert 0 < TX <= 64 and 0 < TY <= 64
    assert 4 * TY <= 127, 'H > 1240 not supported (imm8 4T_Y in FUN_00424d70)'
    return TX, TY


def level_rules(W, H):
    """Values of the patch rules (see P) for a battle resolution W x H."""
    TX, TY = level_check(W, H)
    SXX, SXY = 128 - TX, 128 - TY              # max scroll in tiles (orig 116 = 0x74 for both)
    R = {
        'SX_X': SXX, 'SX_Y': SXY, 'T_X': TX, 'T_Y': TY, 'T-1_X': TX - 1, 'T-1_Y': TY - 1,
        '2T_X': 2 * TX, '2T_Y': 2 * TY, '-2T_X': -2 * TX, '-2T_Y': -2 * TY, '4T_X': 4 * TX, '4T_Y': 4 * TY,
        '2T+2_X': 2 * TX + 2, '2T+2_Y': 2 * TY + 2,
        'MB_X': 0xF + TX + 2, 'MB_Y': 0xF + TY + 2,               # minimap view-box far edge (orig 0x1d)
        'MMC_X': -(15 + TX // 2), 'MMC_Y': -(15 + TY // 2),       # minimap click centring (orig -0x15)
        'HALF_X': TX // 2, 'HALF_Y': TY // 2,                     # centre on army (orig 6)
    }
    R.update({
        'W': W, 'W-1': W - 1, 'W-2': W - 2, 'W-5': W - 5, 'W-8': W - 8, 'W-14': W - 14, 'W-31': W - 31,
        'W-32': W - 32, 'W-39': W - 39, 'W-40': W - 40, 'W-64': W - 64,
        'H': H, 'H-1': H - 1, 'H-2': H - 2, 'H-3': H - 3, 'H-5': H - 5, 'H-7': H - 7, 'H-14': H - 14,
        'H-32': H - 32, 'H-39': H - 39, 'H-40': H - 40, 'H-64': H - 64,
        'CX': W // 2, 'CY': H // 2,                 # mouse centre (orig 320,240)
        'PX': 320 + (W - 640) // 2, 'PY': 215 + (H - 480) // 2,   # "paused" picture
        '+DW': W - 640, '+DH': H - 480,             # folded constants: old value + delta
    })
    return R


