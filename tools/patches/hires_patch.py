"""Hi-res battle patch for Vlad Tepes Dracula 1.0 (Dracula.exe 611328 bytes, 1997-11-20).

Prototype 1: whole game runs at W x H; the battle view (right of the 160px side panel)
becomes (W-160) x H. Because the original reuses one register/constant for the x and the y
scroll limit and tile count, this prototype requires a SQUARE battle view: W - 160 == H.

Usage:  py -I hires_patch.py <no-CD Dracula.exe> <output exe> [W H] [--fixed] [--panel=stone|bottom|tall]
        [--tb=icons|iconsonly|rows|raised|none] [--grp=none|row9|grid10] [--zoom=none] [--compose=none]
        [--disp=WxH]
        (default 1280 720; --panel = how the 160x480 side panel is extended to H, see panel_segments;
        --tb = select-by-type buttons below the help box, --grp = control-group buttons below them (needs
        --tb=icons/iconsonly); default iconsonly + grid10 = user's choice 2026-11-26, see tb_layout)

Default (mode switching): a new PE section ".hires" holds a hook that runs before every frame of the
main loop (FUN_00415d30) and switches the DirectDraw mode: battle (state 2/3) at W x H, everything
else (menu, council, cinema) at the original 640x480. --fixed = whole game at W x H (prototype 1).

Every entry is (VA, expected instruction bytes, rule). The tool checks the bytes before patching
and only rewrites the trailing immediate/displacement of the instruction.
"""
import struct, sys

# --- public version: original game bytes are not stored in this file. O() reads them from the EXE given on
# --- the command line and checks them against a SHA-256 prefix (generated by redact_patch_script.py).
import hashlib as _hl
_O_BASE = None
def O(off, n, h):
    global _O_BASE
    if _O_BASE is None:
        _O_BASE = open([a for a in sys.argv[1:] if not a.startswith('--')][0], 'rb').read()
    b = _O_BASE[off:off + n]
    if _hl.sha256(b).hexdigest()[:16] != h:
        sys.exit(f'input EXE does not match at file offset 0x{off:x} - wrong Dracula.exe version?')
    return b.hex()

