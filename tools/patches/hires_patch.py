def text_off(va): return va - 0x401000 + 0x400
def data_off(va): return va - 0x46a000 + 0x68c00

def apply_level(data, R, BLOCKS):
    """Rewrite every W/H-dependent .text site (P rules + BLOCKS) for one resolution. Returns the count."""
    n = 0
    for va, ins_hex, rule in P:
        ins = bytes.fromhex(ins_hex)
        off = text_off(va)
        cur = bytes(data[off:off + len(ins)])
        if cur != ins:
            sys.exit(f'0x{va:x}: expected {ins.hex()} found {cur.hex()} - aborting, nothing written')
        if rule.startswith('+'):
            old = struct.unpack('<i', ins[-4:])[0]
            new = old + R[rule]
        else:
            new = R[rule]
        # decide immediate size: imm32 if the instruction ends with a 4-byte value, else imm8/disp8
        if len(ins) >= 5 and ins[0] not in (0x83, 0x8d) or (ins[0] == 0x8d and len(ins) >= 6):
            data[off + len(ins) - 4:off + len(ins)] = struct.pack('<i', new)
        else:
            if not -128 <= new <= 127:
                sys.exit(f'0x{va:x}: value {new} does not fit in 8 bits')
            data[off + len(ins) - 1] = new & 0xff
        n += 1
    for va, old_hex, new_hex in BLOCKS:
        off = text_off(va)
        cur = bytes(data[off:off + len(old_hex) // 2])
        if cur != bytes.fromhex(old_hex):
            sys.exit(f'0x{va:x}: expected {old_hex} found {cur.hex()} - aborting, nothing written')
        data[off:off + len(new_hex) // 2] = bytes.fromhex(new_hex)
        n += 1
    return n


