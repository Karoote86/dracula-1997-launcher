def add_section(data, name, payload, chars=0xE0000020):
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    nsec = struct.unpack_from('<H', data, pe + 6)[0]
    optsz = struct.unpack_from('<H', data, pe + 20)[0]
    opt = pe + 24
    salign, falign = struct.unpack_from('<II', data, opt + 32)
    sec = opt + optsz
    last = sec + (nsec - 1) * 40
    lva, lvs = struct.unpack_from('<II', data, last + 8)[1], struct.unpack_from('<I', data, last + 8)[0]
    up = lambda v, al: (v + al - 1) // al * al
    va = up(lva + lvs, salign)
    raw = up(len(data), falign)
    rsize = up(len(payload), falign)
    hdr = sec + nsec * 40
    assert hdr + 40 <= struct.unpack_from('<I', data, opt + 60)[0], 'no room for a section header'
    struct.pack_into('<8sIIIIIIHHI', data, hdr, name.encode().ljust(8, b'\0'), len(payload), va, rsize, raw,
                     0, 0, 0, 0, chars)
    struct.pack_into('<H', data, pe + 6, nsec + 1)
    struct.pack_into('<I', data, opt + 56, up(va + len(payload), salign))   # SizeOfImage
    data += b'\0' * (raw - len(data))
    data += payload + b'\0' * (rsize - len(payload))
    return 0x400000 + va


