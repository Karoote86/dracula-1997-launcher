def council_mask():
    """Black torn edges/corners of the council parchment (Art\\Council.art rows 0..479, the strategy-map
    background): flood fill of near-black pixels (max(r,g,b) <= 40) from the picture border.
    -> [(y, x0, n, art pixel bytes)] row spans, or None if Council.art is not found (no mask)."""
    import os
    here = os.path.dirname(os.path.abspath(__file__))
    for p in (os.path.join(os.path.dirname(os.path.abspath(dst)), 'Art', 'Council.art'),
              os.path.join(here, '..', 'Dracula', 'Art', 'Council.art'),
              os.path.join(here, '..', 'Dracula_Original', 'Art', 'Council.art')):
        if os.path.exists(p): break
    else:
        print('warning: Art\\Council.art not found - strategy map edges stay black'); return None
    d = open(p, 'rb').read()
    assert d[0] == 10 and d[2] == 1 and d[3] == 8 and d[-769] == 12, 'unexpected Council.art format'
    bpl = struct.unpack_from('<H', d, 66)[0]
    pal = d[-768:]
    px, i = bytearray(), 128
    while len(px) < bpl * 480:                    # PCX RLE (only the first 480 rows are needed)
        c = d[i]; i += 1
        if c >= 0xc0: px += bytes([d[i]]) * (c & 0x3f); i += 1
        else: px.append(c)
    dark = [max(pal[3 * v:3 * v + 3]) <= 40 for v in range(256)]
    m = bytearray(640 * 480)
    st = [(x, y) for x in range(640) for y in (0, 479)] + [(x, y) for y in range(480) for x in (0, 639)]
    while st:
        x, y = st.pop()
        if 0 <= x < 640 and 0 <= y < 480 and not m[y * 640 + x] and dark[px[y * bpl + x]]:
            m[y * 640 + x] = 1
            st += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    spans = []
    for y in range(480):
        x = 0
        while x < 640:
            if not m[y * 640 + x]: x += 1; continue
            x0 = x
            while x < 640 and m[y * 640 + x]: x += 1
            spans.append((y, x0, x - x0, bytes(px[y * bpl + x0:y * bpl + x])))
    return spans


def build_cave(base, imports, levels):
    a = Asm(base)
    HI_W, HI_H, LO_W, LO_H, OLDOFF, TMP, CLOSING, CLOSEAT = (base + i * 4 for i in range(8))
    SEGSV, TEXTSV, BTNSV, T4, ZCUR, ZACC, ZMX, ZMY, ZDONE = (base + 0x20 + i * 4 for i in range(9))
    start = [(lw, lh) for lw, lh, _ in levels].index((W, H))
    a.raw('', *(DISP if COMPOSE and DISP[0] else (W, H)), 640, 480, 0, 0, 0, 0)   # data block 0x20 bytes
    a.raw('', 0, 0, 0, 4 * TX, start, 0, 0, 0, 0)    # current level's panel/button lists (set below), 4T_X,
    FX = a.here()                                     # zoom level index, wheel delta accumulator, cursor
                                                      # position for the new level + flag (restore after switch)
    a.raw('', 100, *([0] * 24))                       # DDBLTFX (dwSize = 100, dwDDFX at +4)
    def var(*init):
        va = a.here(); a.raw('', *init); return va
    CURW, CURH = var(640), var(480)                   # current display mode (set by SwitchMode)
    if COMPOSE:                                       # compose mode state (see the header comment)
        dw, dh = DISP
        pw = dh * 160 // 720
        DISPW, DISPH, PANW, VIEWPW = var(dw), var(dh), var(pw), var(dw - pw)   # desktop, panel width, view width
        VACT, VNEED, RB, CURVALID = var(0), var(0), var(0), var(0)   # virtual active, resize, real back, cursor
        PMX, PMY, PVY = var(0), var(0), var(0)        # physical mouse, unclamped virtual y (button hit tests)
        LW, LH, LVW = var(W), var(H), var(W - 160)    # level size, view width
        DSTP, SRCP = var(0, 0, pw, dh), var(0, 0, 160, 720)          # panel  -> (0,0,PANW,DISPH)
        DSTV, SRCV = var(pw, 0, dw, dh), var(160, 0, W, H)           # view   -> (PANW,0,DISPW,DISPH)
        DSTC, SRCC = var(0, 0, 0, 0), var(0, 0, 0, 0)                # cursor (recorded from DrawCursor)
        ZUX, ZUY, ZWX, ZWY = var(0), var(0), var(-1), var(-1)        # last zoom: unclamped / written scroll px
        ZMX0, ZMY0 = var(-1), var(-1)                                # and the physical mouse at that time
        OLDVB, OLDVOFF = var(0), var(0)                              # vremake
        mw = 640 * dh // 480                                         # menu/council picture, centred
        MOFFX = (dw - mw) // 2
        DSTM_X0, DSTM_X1 = MOFFX, MOFFX + mw
        DSTM, SRCM = var(MOFFX, 0, MOFFX + mw, dh), var(0, 0, 640, 480)
        if MBLUR:             # blurred bars: see 'bars'. Bars rendered at 1/2 resolution (BW x BH each).
            assert MOFFX % 2 == 0 and dh % 2 == 0 and MOFFX >= 16, 'blurred bars need even side bars'
            BW, BH = MOFFX // 2, dh // 2
            crop = (480 * dw // 640 - dh) // 2               # cover fill: picture scaled to the screen width
            def wsplit(c, nmax):                             # cell coordinate -> (cell index, weight 0..16)
                i0 = max(0, min(nmax, int(c // 1))) if c >= 0 else 0
                w = 0 if c < 0 else max(0, min(16, round((c - i0) * 16)))
                return i0, w
            colt = []
            for bx in range(2 * BW):
                sx = 2 * bx + 1 if bx < BW else DSTM_X1 + 2 * (bx - BW) + 1
                i0, wx = wsplit((sx * 640 / dw - 8) / 16, 38)
                dist = (BW - 1 - bx) if bx < BW else (bx - BW)   # 0 next to the picture
                colt += [i0 * 12, wx, 115 - dist * 60 // max(1, BW - 1)]
            rowt = []
            for by in range(BH):
                j0, wy = wsplit(((2 * by + 1 + crop) * 640 / dw - 8) / 16, 28)
                rowt += [j0 * 40 * 12, wy]
            COLT, ROWT = var(*colt), var(*rowt)
            BAYER = var(*[v * 64 for v in (0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5)])   # 4x4 dither
            # PALETTEENTRY r,g,b,flags (flags cleared): current, last frame's, the one TABLE was built for
            PALNEW, PALPREV, PALCUR = var(*([0] * 256)), var(*([0] * 256)), var(*([0] * 256))
            PCHG = var(0)                                    # palette changed in the last frame
            TABLE = var(*([0] * 8192))                       # RGB555 over 0..127 -> nearest index (bytes)
            DITH = var(0)
            GRID = var(*([0] * (40 * 30 * 3)))               # 16x16-px cell averages, r,g,b dwords
            DDSD = var(*([0] * 27))                          # DDSURFACEDESC (108 bytes) for Lock
            (GJ, GI, GB, SPTR, SPITCH, DPTR, DPITCH, RY, RX, ROFF, WXV, WYV, FAC, BARS, TRV, TGV, TBV) = \
                (var(0) for _ in range(17))
            SRCBL, DSTBL = var(0, 0, BW, BH), var(0, 0, MOFFX, dh)
            SRCBR, DSTBR = var(BW, 0, 2 * BW, BH), var(DSTM_X1, 0, dw, dh)
            CSPANS = council_mask()  # council parchment: black torn edges -> blurred background ('cmask')
            if CSPANS:
                colm = []            # per picture column x: cell offset i0*12, wx, screen x0, width
                for x in range(640):
                    sx0, sx1 = MOFFX + x * mw // 640, MOFFX + (x + 1) * mw // 640
                    i0, wx = wsplit(((sx0 + sx1) / 2 * 640 / dw - 8) / 16, 38)
                    colm += [i0 * 12, wx, sx0, sx1 - sx0]
                rowm = []            # per picture row y: cell row offset j0*480, wy, screen y0, height
                for y in range(480):
                    sy0, sy1 = y * dh // 480, (y + 1) * dh // 480
                    j0, wy = wsplit((((sy0 + sy1) / 2 + crop) * 640 / dw - 8) / 16, 28)
                    rowm += [j0 * 40 * 12, wy, sy0, sy1 - sy0]
                COLM, ROWM = var(*colm), var(*rowm)
                MART = a.data(b''.join(sp[3] for sp in CSPANS))   # the art pixels of all spans
                while len(a.b) % 4: a.b += b'\0'
                recs, p = [], MART
                for y, x0, n, bs in CSPANS:
                    recs += [y, x0, n, p]; p += n
                MSPANS = var(*recs, 0, 0, 0, 0)                  # {y, x0, n, art ptr}, n 0 = end
                CMS, CMX, CMEND, CMA, CMY, CMROW, CMR, CMH = (var(0) for _ in range(8))
    # Per level: panel extension {dst RECT, src RECT, flags} (36 bytes; flags = ddfx | KEYED) + the static
    # button segments, one 0 terminator; button texts {x, y, str, font variable} (16 bytes, str 0 = end);
    # per button a pressed look (segs + texts); the button records (48 bytes, see below).
    strs = {}
    def cstr(s):
        if s not in strs: strs[s] = a.data(s.encode('ascii') + b'\0')
        return strs[s]
    def textlist(tx):
        refs = [(x, y, cstr(s), f) for x, y, s, f in tx]
        va = a.here()
        for r in refs: a.raw('', *r)
        a.raw('', 0, 0, 0, 0)
        return va
    def seglist(segs):                                # absolute sheet coords
        for s in segs: a.raw('', *s[:8], s[8] if len(s) > 8 else 0)
        a.raw('', *([0] * 9))
    HAS_GRP, lrecs, panels = False, [], {}
    for lw, lh, blob in levels:
        ph = 720 if COMPOSE else lh                   # compose: the same 720 panel at every level
        if ph not in panels:
            while len(a.b) % 4: a.b += b'\0'
            segs_va = a.here()
            for seg in panel_segments(PANEL, ph):
                dx0, dy0, dx1, dy1, sx0, sy0, sx1, sy1 = seg[:8]
                a.raw('', dx0, dy0, dx1, dy1, sx0, PANEL_Y0 + sy0, sx1, PANEL_Y0 + sy1,
                      seg[8] if len(seg) > 8 else 0)
            tb_segs, tb_texts, tb_btns = tb_layout(TB, GRP, ph)
            HAS_GRP |= any(b['type'] >= 8 for b in tb_btns)
            seglist(tb_segs)
            texts_va = textlist(tb_texts)
            recs = []
            for b in tb_btns:
                psegs = a.here(); seglist(b['psegs'])
                recs.append((b, psegs, textlist(b['ptexts']), cstr(b['help']), cstr(b['help2'])))
            while len(a.b) % 4: a.b += b'\0'
            btns_va = a.here()    # +0 hit rect x0,y0,x1,y1 | +16 type (8 + g = group g) | +20 count x (1 digit),
            for b, ps, pt, hs, h2 in recs:   # +24 count y (0 = none) | +28 help line 1 | +32 pressed segs |
                a.raw('', *b['rect'], b['type'], b['cx'], b['cy'], hs, ps, pt, h2, b['shift'])   # +36 pr. texts
            a.raw('', *([0] * 12))                    # +40 help line 2 | +44 x shift per extra digit; x1 0 = end
            panels[ph] = (segs_va, texts_va, btns_va)
        ltx, lty = level_check(lw, lh)
        lrecs.append([lw, lh, ltx, lty, *panels[ph], 4 * ltx, blob])
    struct.pack_into('<III', a.b, 0x20, *lrecs[start][4:7])
    if ZOOM:                  # SITES {VA, length}, 0-terminated; per level a blob with all their bytes;
        SITES = a.here()      # level table (36 bytes): W, H, TX, TY, segs, texts, buttons, 4T_X, blob
        for va, ln in ZSITES: a.raw('', va, ln)
        a.raw('', 0, 0)
        for r in lrecs: r[8] = a.data(r[8])
        while len(a.b) % 4: a.b += b'\0'
        LEVTAB = a.here()
        for r in lrecs: a.raw('', *r)
    TB_PREV, TB_PRESSED = a.here(), a.here() + 4      # LMB state last frame, pressed record (0 = none)
    COUNTS = a.here() + 8                             # living own units per type 0..7, per group (8 + g)
    a.raw('', *([0] * 20))
    MCI, TICK, SENDMSG = imports['mciSendStringA'], imports['GetTickCount'], imports['SendMessageA']
    HWND, STR_STOP, STR_CLOSE = 0x5ea738, 0x470154, 0x470194   # "stop cdaudio" (patched), "close cdaudio"
    MX, MY, FONT, ISKEY, SOUND = 0x58fcc8, 0x58fccc, 0x5ea728, 0x421a50, 0x424c60   # IsKeyDown(vk), sound(id)
    DRAWTEXT, DRAWNUM = 0x41b640, 0x41b870            # (x, y, str | int, font, dst) cdecl
    LP, UNITS, TOTAL, OWN, SELCNT = 0x5e87bc, 0x5e87c8, 0x5e8700, 0x5e8730, 0x7a0f98

    # ---- WndProc wrapper (registered instead of 0x41d2a0): first WM_CLOSE only stops and closes the
    # CD music (ogg-winmm) and schedules the real close 700 ms later. Closing while ogg-winmm's player
    # thread is still busy deadlocks ("stop cdaudio wait") or leaves an unkillable process.
    a.label('wndproc')
    if ZOOM:                                           # WM_MOUSEWHEEL: ZACC += wheel delta (high word of
        a.raw('817c2408', 0x20a); a.j8(0x75, 'wp_nowheel')   # wParam), return 0; the hook turns it into
        a.raw('0fbf44240e'); a.raw('0105', ZACC)               # zoom steps (120 = one notch)
        a.raw('33c0 c21000')
        a.label('wp_nowheel')
    a.raw('837c240810'); a.j8(0x75, 'wp_orig')        # cmp dword [esp+8],WM_CLOSE / jne
    a.raw('833d', CLOSING); a.raw('00'); a.j8(0x75, 'wp_orig')   # already closing -> pass through
    a.raw('c705', CLOSING, 1)
    a.raw('6a00 6a00 6a00 68', STR_STOP); a.raw('ff15', MCI)
    a.raw('6a00 6a00 6a00 68', STR_CLOSE); a.raw('ff15', MCI)
    a.raw('ff15', TICK); a.raw('05', 700); a.raw('a3', CLOSEAT)
    a.raw('33c0 c21000')                               # return 0 (stdcall, 4 args)
    a.label('wp_orig')
    a.rel32(0xe9, 0x41d2a0)
    STATE, SCRW, SCRH, RECTR, RECTB = 0x5e9ca8, 0x5ea518, 0x5ea51c, 0x5ea718, 0x5ea71c
    DD, PRIM, BACK, OFF, PAL, BLACK, REDRAW = 0x5ea72c, 0x5ea750, 0x5ea754, 0x5ea75c, 0x5ea704, 0x5ea720, 0x49219c
    CREATE_OFF, FILL, MAINLOOP = 0x41b530, 0x41be50, 0x415d30

    def release(addr, lbl):                           # IUnknown::Release + clear the variable
        a.raw('a1', addr); a.raw('85c0'); a.j8(0x74, lbl)
        a.raw('50 8b08 ff5108'); a.raw('c705', addr, 0); a.label(lbl)
    def copy640(dst_var, src_var, lbl):               # BltFastOpaque(0,0,&640x480,[dst],[src]) if both exist
        a.raw('833d', dst_var); a.raw('00'); a.j8(0x74, lbl)
        a.raw('833d', src_var); a.raw('00'); a.j8(0x74, lbl)
        a.raw('ff35', src_var); a.raw('ff35', dst_var); a.raw('68', 0x46b7a8); a.raw('6a00 6a00')
        a.rel32(0xe8, 0x41bb20); a.raw('83c414')
        a.label(lbl)

    # ---- ModeHook: called instead of FUN_00415d30 once per frame
    a.label('hook')
    a.raw('60')                                       # pushad
    # delayed close: once the music had time to stop, send the real WM_CLOSE and skip this frame
    a.raw('833d', CLOSING); a.raw('01'); a.j8(0x75, 'nclose')
    a.raw('ff15', TICK); a.raw('3b05', CLOSEAT); a.j8(0x72, 'nclose')   # jb: not yet
    a.raw('c705', CLOSING, 2)
    a.raw('6a00 6a00 6a10 ff35', HWND); a.raw('ff15', SENDMSG)
    a.raw('61 c3')                                    # popad / ret (no frame: surfaces are gone)
    a.label('nclose')
    if ZOOM:                                          # battle (state 2): whole wheel notches -> zoom steps
        a.raw('833d', STATE); a.raw('02'); a.j8(0x75, 'zclr')
        a.raw('833d', 0x58fcd0 + 0xc); a.raw('00'); a.j8(0x74, 'zchk')   # battle input idle (no box/drag)
        a.label('zclr')
        a.raw('c705', ZACC, 0); a.j8(0xeb, 'nozoom')  # elsewhere: forget the wheel
        a.label('zchk')
        a.raw('a1', ZACC); a.raw('99 b978000000 f7f9'); a.raw('8915', ZACC)   # eax = notches, edx = rest
        a.raw('85c0'); a.j8(0x74, 'nozoom')
        a.raw('f7d8'); a.rel32(0xe8, 'zoom')         # wheel forward (> 0) = zoom in = smaller level
        a.label('nozoom')
